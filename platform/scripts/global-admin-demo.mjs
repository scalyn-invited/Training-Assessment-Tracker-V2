import fs from 'node:fs';
import path from 'node:path';
import {DatabaseSync,backup} from 'node:sqlite';
import {spawnSync} from 'node:child_process';
import {demoEnvironment} from './realistic-demo.mjs';
const name=process.argv.find(x=>x.startsWith('--name='))?.slice(7);
if(!name || !process.argv.includes('--upgrade')) throw Error('Explicit --name=realistic-demo... and --upgrade required. Never creates or reseeds a database.');
const env=demoEnvironment(name),root=env.TRAINING_DEMO_ROOT;
if(!fs.existsSync(env.DB_DATABASE)) throw Error('Existing demo required.');
const run=args=>{const r=spawnSync('php',['-d','extension=gd',...args],{env,stdio:'inherit',windowsHide:true});if(r.status!==0)throw Error('Stopped without continuing: '+args.join(' '));};
run(['artisan','training:demo-global-admin','--database='+env.DB_DATABASE,'--check']);
const snapshot=path.join(root,'global-admin-backups',new Date().toISOString().replaceAll(/[:.]/g,'-'));
fs.mkdirSync(snapshot,{recursive:true});
const db=new DatabaseSync(env.DB_DATABASE,{readOnly:true}); await backup(db,path.join(snapshot,'before.sqlite')); db.close();
fs.cpSync(path.join(root,'private'),path.join(snapshot,'private'),{recursive:true});
fs.copyFileSync(path.join(root,'manifest.json'),path.join(snapshot,'manifest.json'));
console.log('Preserved demo snapshot: '+snapshot);
run(['artisan','migrate','--force','--no-interaction']);
run(['artisan','training:demo-global-admin','--database='+env.DB_DATABASE]);
